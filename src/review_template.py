
import csv
from pathlib import Path


# ==========================================================
# 1. PROJECT PATHS
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

EVALUATION_DIR = PROJECT_ROOT / "evaluation"

AUDIT_FILE = EVALUATION_DIR / "legal_quality_report.csv"

REVIEW_FILE = EVALUATION_DIR / "legal_manual_review.csv"


# ==========================================================
# 2. REVIEW CONFIGURATION
# ==========================================================

REVIEW_COLUMNS = [
    "manual_review_status",
    "verified_source",
    "verified_section",
    "correction_required",
    "review_notes",
    "reviewer",
]

DEFAULT_REVIEW_STATUS = "not_reviewed"

VALID_REVIEW_STATUSES = [
    "not_reviewed",
    "verified_correct",
    "corrected_from_source",
    "exclude_corrupted",
    "exclude_duplicate",
    "retain_missing_metadata",
    "needs_further_investigation",
]

# Additional tracking fields
TRACKING_COLUMNS = [
    "review_key",
    "audit_record_present",
]

# These fields help match the same record between audit runs.
IDENTITY_FIELDS = [
    "record_id",
    "line_number",
    "source_record_number",
    "act_id",
    "chunk_id",
    "title",
    "section_number",
    "source_url",
]


# ==========================================================
# 3. CSV HELPERS
# ==========================================================

def read_csv(path):

    if not path.exists():
        return [], []

    with open(
        path,
        "r",
        newline="",
        encoding="utf-8-sig",
    ) as file:

        reader = csv.DictReader(file)

        fieldnames = reader.fieldnames or []
        rows = list(reader)

    return rows, fieldnames


def clean_value(value):
    """Normalize CSV values for record matching."""

    if value is None:
        return ""

    return str(value).strip()


# ==========================================================
# 4. CREATE STABLE REVIEW KEY
# ==========================================================

def create_review_key(record):
    """
    Identify records across audit runs.

    Prefer generated record_id.
    Use source record number or composite metadata
    as fallback.
    """

    record_id = clean_value(record.get("record_id"))

    if record_id:
        return f"record_id::{record_id}"

    source_number = clean_value(
        record.get("source_record_number")
    )

    if source_number:
        return f"source_record_number::{source_number}"

    # Fallback for older audit CSV files
    composite_fields = [
        "act_id",
        "chunk_id",
        "title",
        "section_number",
        "source_url",
    ]

    values = [
        clean_value(record.get(field))
        for field in composite_fields
    ]

    if any(values):
        return "composite::" + "||".join(values)

    line_number = clean_value(record.get("line_number"))

    if line_number:
        return f"line_number::{line_number}"

    raise ValueError(
        "Could not identify a record. "
        "The audit row has no usable identity fields."
    )


# ==========================================================
# 5. LOAD EXISTING REVIEW HISTORY
# ==========================================================

def load_existing_reviews():

    rows, _ = read_csv(REVIEW_FILE)

    review_map = {}

    for row in rows:

        key = clean_value(row.get("review_key"))

        # Support review files generated by older versions
        if not key:
            try:
                key = create_review_key(row)
            except ValueError:
                continue

        # Keep existing manual values.
        # If duplicate review keys exist, retain the latest row.
        review_map[key] = row

    return review_map


# ==========================================================
# 6. MERGE CURRENT AUDIT WITH REVIEW HISTORY
# ==========================================================

def merge_reviews(audit_rows, existing_reviews):

    merged_rows = []
    current_keys = set()

    for audit_row in audit_rows:

        key = create_review_key(audit_row)

        current_keys.add(key)

        previous = existing_reviews.get(key, {})

        # Start with all latest audit information
        merged = dict(audit_row)

        # Preserve manual review decisions
        for column in REVIEW_COLUMNS:

            previous_value = clean_value(
                previous.get(column)
            )

            if previous_value:
                merged[column] = previous_value

            elif column == "manual_review_status":
                merged[column] = DEFAULT_REVIEW_STATUS

            else:
                merged[column] = ""

        # Add tracking information
        merged["review_key"] = key
        merged["audit_record_present"] = "yes"

        merged_rows.append(merged)

    # Preserve historical review records that are absent
    # from the latest audit. Do not silently delete them.
    for key, previous in existing_reviews.items():

        if key in current_keys:
            continue

        historical = dict(previous)

        historical["review_key"] = key
        historical["audit_record_present"] = "no"

        merged_rows.append(historical)

    return merged_rows


# ==========================================================
# 7. SAVE UPDATED REVIEW TEMPLATE
# ==========================================================

def save_review_file(rows, audit_fields, old_fields):

    EVALUATION_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Preserve existing columns and add new audit fields.
    fieldnames = list(dict.fromkeys(
        audit_fields
        + old_fields
        + REVIEW_COLUMNS
        + TRACKING_COLUMNS
    ))

    with open(
        REVIEW_FILE,
        "w",
        newline="",
        encoding="utf-8-sig",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
            extrasaction="ignore",
        )

        writer.writeheader()
        writer.writerows(rows)

    print("\nUpdated manual review file:")
    print(REVIEW_FILE)


# ==========================================================
# 8. PRINT SUMMARY
# ==========================================================

def print_summary(rows):

    status_counts = {}

    current_count = 0
    historical_count = 0
    reviewed_count = 0

    for row in rows:

        status = clean_value(
            row.get("manual_review_status")
        ) or DEFAULT_REVIEW_STATUS

        status_counts[status] = (
            status_counts.get(status, 0) + 1
        )

        if row.get("audit_record_present") == "yes":
            current_count += 1
        else:
            historical_count += 1

        if status != DEFAULT_REVIEW_STATUS:
            reviewed_count += 1

    print("\n" + "=" * 60)
    print("LEGAL DATASET MANUAL REVIEW SUMMARY")
    print("=" * 60)

    print("Total review records:", len(rows))
    print("Currently flagged records:", current_count)
    print("Historical review records:", historical_count)
    print("Records with review decisions:", reviewed_count)
    print("Records awaiting review:", status_counts.get(
        DEFAULT_REVIEW_STATUS, 0
    ))

    print("\nReview status distribution:")

    for status, count in sorted(status_counts.items()):
        print(f"{status}: {count}")

    print("\nAvailable review statuses:")

    for status in VALID_REVIEW_STATUSES:
        print("-", status)

    print("=" * 60)


# ==========================================================
# 9. MAIN
# ==========================================================

def main():

    if not AUDIT_FILE.exists():
        raise FileNotFoundError(
            f"Quality audit report not found:\n{AUDIT_FILE}\n\n"
            "Run the quality audit first:\n"
            "python -m src.quality_audit"
        )

    print("Loading latest quality audit...")

    audit_rows, audit_fields = read_csv(AUDIT_FILE)

    print("Flagged records in latest audit:", len(audit_rows))

    print("Loading previous manual review decisions...")

    existing_reviews = load_existing_reviews()

    print("Existing review decisions:", len(existing_reviews))

    old_rows, old_fields = read_csv(REVIEW_FILE)

    print("Merging review history...")

    merged_rows = merge_reviews(
        audit_rows,
        existing_reviews,
    )

    save_review_file(
        merged_rows,
        audit_fields,
        old_fields,
    )

    print_summary(merged_rows)

    print("\nMANUAL REVIEW TEMPLATE UPDATED SUCCESSFULLY.")


if __name__ == "__main__":
    main()
